#!/usr/bin/env python3
"""
selfportrait.py -- write a Piebald program whose source *is* a piebald coat,
and which prints that same coat when it runs.

    python tools/selfportrait.py [-o examples/coat.pie] [--width 64]
                                 [--height 56] [--seed 7] [--coverage 0.42]

Every character in the picture is a live instruction; there is no filler.

Each pixel of the coat is printed as '@' (64) for a dark patch or ' ' (32)
for white.  These differ by one shift, so a pixel's instruction is just the
change from its previous value:

    white -> dark   <        dark -> dark   6   (sets a bit that is already set)
    dark  -> white  >        white -> white     (nothing)

The dark patches are therefore drawn in solid instructions, outlined with
< along their top edges and > just below their bottom edges.

Each pixel has two wires, X (even column) and Y (odd column), which take
turns: line r of the coat is built on X when r is even and on Y when r is
odd, while the other wire prints line r-1.  So each wire's instruction encodes
the change from line r-2 to line r, and the print instructions '.' are woven
through the picture instead of taking whole rows of their own.
"""
import argparse
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from piebaldify import coat  # noqa: E402


def change(before, after):
    if before and after:
        return "6"
    if after:
        return "<"
    if before:
        return ">"
    return " "


def build(mask):
    H, W = len(mask), len(mask[0])
    NL = 2 * W                       # the newline wire
    width = NL + 1
    white = [False] * W

    def blank():
        return [" "] * width

    rows = []
    r = blank()
    for c in range(2 * W):
        r[c] = "5"                   # every wire starts white: 32 = ' '
    r[NL] = "3"
    rows.append(r)

    for line in range(H + 1):
        r = blank()
        build_par = line % 2         # this line is built on X (0) or Y (1)
        if line < H:
            before = mask[line - 2] if line >= 2 else white
            for i in range(W):
                r[2 * i + build_par] = change(before[i], mask[line][i])
        if line >= 1:                # the other wire holds line-1: print it
            for i in range(W):
                r[2 * i + 1 - build_par] = "."
            r[NL] = "."
        else:
            r[NL] = "1"              # finish the newline: 8 | 2 = 10
        rows.append(r)
    return ["".join(r).rstrip() for r in rows]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output")
    ap.add_argument("--width", type=int, default=64, help="pixels across (the source is twice as wide)")
    ap.add_argument("--height", type=int, default=56)
    ap.add_argument("--coverage", type=float, default=0.42)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    # A source pixel is two characters wide and one tall, so roughly square.
    mask = coat(args.width, args.height, args.coverage, random.Random(args.seed), aspect=1.0)
    rows = build(mask)
    text = (
        "# A self-portrait.  This program is a piebald coat, and it prints itself as one:\n"
        "# the instructions < 6 > draw the dark patches and also compute them.\n"
        f"# Generated by tools/selfportrait.py --seed {args.seed}; see that file for how it works.\n"
        + "\n".join(rows) + "\n")
    if args.output:
        with open(args.output, "w", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
